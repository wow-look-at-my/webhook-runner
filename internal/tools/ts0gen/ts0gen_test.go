func TestTS0URL(t *testing.T) {
	got := ts0URL(2, "linux", "amd64")
	want := "https://dl.pazer.build/ts0?v=2&os=linux&arch=amd64"
	assert.Equal(t, want, got)

	// ts0 is platform-neutral (any-platform alias on buildhost), so other
	// GOOS/GOARCH values pass straight through.
	got = ts0URL(7, "darwin", "arm64")
	want = "https://dl.pazer.build/ts0?v=7&os=darwin&arch=arm64"
	assert.Equal(t, want, got)

}

func TestTS0CachePath(t *testing.T) {
	got := ts0CachePath("/home/u/.cache", 2)
	want := filepath.Join("/home/u/.cache", "webhook-runner-ts0", "v2", "ts0.cjs")
	assert.Equal(t, want, got)

	// The .cjs extension is load-bearing (ESM mis-parse otherwise) — keep it.
	assert.Equal(t, ".cjs", filepath.Ext(got))

}

func TestNodeMajor(t *testing.T) {
	cases := []struct {
		in      string
		want    int
		wantErr bool
	}{
		{"v22.22.2\n", 22, false},
		{"v9.1.0", 9, false},
		{"22.0.0", 22, false},
		{"not-a-version", 0, true},
		{"", 0, true},
	}
	for _, c := range cases {
		got, err := nodeMajor(c.in)
		if c.wantErr {
			assert.NotNil(t, err)

			continue
		}
		assert.Nil(t, err)

		assert.Equal(t, c.want, got)

	}
}

