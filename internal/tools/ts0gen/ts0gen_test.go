func TestSameIgnoringFetchDate(t *testing.T) {
	a := []byte(declHeader("https://example.com/x.d.ts", "2026-07-13") + "export const x = 1;\n")
	b := []byte(declHeader("https://example.com/x.d.ts", "2026-08-01") + "export const x = 1;\n")
	assert.True(t, sameIgnoringFetchDate(a, b))

	assert.True(t, sameIgnoringFetchDate(a, a))

	c := []byte(declHeader("https://example.com/x.d.ts", "2026-07-13") + "export const x = 2;\n")
	assert.False(t, sameIgnoringFetchDate(a, c))

	d := []byte(declHeader("https://example.com/OTHER.d.ts", "2026-07-13") + "export const x = 1;\n")
	assert.False(t, sameIgnoringFetchDate(a, d))

}
